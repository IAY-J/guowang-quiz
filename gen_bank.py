def main():
    assert len(QUESTIONS) == 165, len(QUESTIONS)
    questions = []
    for index, (category, section, qtype, stem, options, answer, score, reason) in enumerate(QUESTIONS, start=1):
        category = REMAP.get(index, category)
        if qtype == "judge":
            options = ["正确", "错误"]
            answer = True if answer else False
        item = {
            "id": index,
            "category": category,
            "section": section,
            "type": qtype,
            "stem": stem,
            "options": options,
            "answer": answer,
            "score": score,
            "reason": reason,
        }
        if section == "资料分析":
            item["group"] = 1 if index <= 160 else 2
        questions.append(item)
    if PDF_SOURCE.exists():
        with pdfplumber.open(str(PDF_SOURCE)) as pdf:
            for q in questions:
                crops = IMAGE_CROPS.get(q["id"])
                if crops:
                    q["images"] = [crop_data_uri(pdf, pi, bbox) for pi, bbox in crops]
    base_total = sum(q["score"] for q in questions)
    assert abs(base_total - 100) < 1e-9, base_total
    extra = Path(__file__).with_name("tongxin-moni-kaoshi.json")
    if extra.exists():
        extra_data = json.loads(extra.read_text(encoding="utf-8"))
        existing = {json.dumps([q["type"], q["stem"], q["options"], q["answer"], q["reason"], q.get("images", [])], ensure_ascii=False) for q in questions}
        max_id = max(q["id"] for q in questions)
        for q in extra_data["questions"]:
            fp = json.dumps([q["type"], q["stem"], q["options"], q["answer"], q["reason"], q.get("images", [])], ensure_ascii=False)
            if fp in existing:
                continue
            existing.add(fp)
            max_id += 1
            q = dict(q)
            q["id"] = max_id
            questions.append(q)
    bank = {
        "title": "国网通信刷题",
        "categories": CATEGORIES,
        "composite": COMPOSITE,
        "questions": questions,
    }
    total = sum(q["score"] for q in questions)
    out = Path(__file__).with_name("sample-bank.json")
    out.write_text(json.dumps(bank, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    js_out = Path(__file__).with_name("bank-data.js")
    js_out.write_text(
        "window.BUNDLED_BANK = " + json.dumps(bank, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(questions)} questions, full score {total:g} to {out} and {js_out}")


if __name__ == "__main__":
    main()
